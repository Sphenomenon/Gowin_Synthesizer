# Realtek RTL8723D S1 RX IQK sequence, adapted from halphyrf_8723d.c.
import time


def calibrate_s1(w):
    w.stage('rx_iq_calibration_s1')
    adda=[0x85c,0xe6c,0xe70,0xe74,0xe78,0xe7c,0xe80,0xe84,0xe88,0xe8c,
          0xed0,0xed4,0xed8,0xedc,0xee0,0xeec]
    bb=[0xc04,0xc08,0x874,0xb68,0xb6c,0x870,0x860,0x864,0xa04,0x948,0x70]
    saved={a:w.r(a,4) for a in adda+bb}
    mac={a:w.r(a) for a in (0x522,0x550,0x551,0x40,0x67,0xc50)}
    grants=w.coex_read(0x38)
    rf_saved={a:w.rf_read(a) for a in (0xdf,0x56)}
    result={}
    def rf_mask(a,m,v):w.rf_write(a,(w.rf_read(a)&~m)|(v&m))
    def writes(items):
        for a,v in items:w.w(a,v,4)
    def shot():
        writes([(0xe48,0xf9000000),(0xe48,0xf8000000)])
        eac=w.poll(0xeac,1<<26,1<<26,4,timeout=.2)
        return eac
    try:
        for a in adda:w.w(a,0x03c00016,4)
        w.w(0x522,0x3f);w.mask(0x550,8,0);w.mask(0x551,8,0);w.mask(0x40,0x20,0)
        w.mask(0xa04,0x0f000000,0x0f000000,4)
        writes([(0xc04,0x03a05611),(0xc08,0x000800e4),(0x874,0x25204200)])
        w.mask(0x67,0x80,0x80);w.mask(0x70,1<<26,1<<26,4)
        w.coex_write(0x38,0xff00)
        writes([(0x948,0x99000000),(0xe28,0),(0xe40,0x01007c00),(0xe44,0x01004800),
                (0xe30,0x18008c1c),(0xe34,0x38008c1c),(0xe50,0x38008c1c),(0xe54,0x38008c1c),
                (0xe38,0x82160000),(0xe3c,0x28160000),(0xe4c,0x0046a911)])
        for a,v in [(0xef,0x80000),(0x33,6),(0x3e,0x5f),(0x3f,0xa7ffb)]:w.rf_write(a,v)
        rf_mask(0xdf,0x800,0x800);rf_mask(0x56,0x600,0)
        w.rf_write(1,0xe0d);w.rf_write(2,0x60d)
        w.w(0xe28,0x80800000,4)
        eac=shot();e94=w.r(0xe94,4);e9c=w.r(0xe9c,4)
        result['step1']={f'{a:04x}':f'{w.r(a,4):08x}' for a in (0xe90,0xe94,0xe98,0xe9c,0xeac)}
        if eac&(1<<28) or (e94>>16)&0x3ff==0x142 or (e9c>>16)&0x3ff==0x42:
            raise RuntimeError(f'RX IQK step 1 failed: {result}')
        w.w(0xe40,0x80007c00|(e94&0x3ff0000)|((e9c>>16)&0x3ff),4)
        writes([(0xe44,0x01004800),(0xe30,0x38008c1c),(0xe34,0x18008c1c),
                (0xe50,0x38008c1c),(0xe54,0x38008c1c),(0xe38,0x82170000),
                (0xe3c,0x28171400),(0xe4c,0x0046a8d1),(0xe28,0)])
        for a,v in [(0xef,0x80000),(0x33,7),(0x3e,0x5f),(0x3f,0xb3fdb)]:w.rf_write(a,v)
        w.w(0xe28,0x80800000,4)
        eac=shot();ea4=w.r(0xea4,4);x=(ea4>>16)&0x3ff;y=(eac>>16)&0x3ff
        result['step2']={f'{a:04x}':f'{w.r(a,4):08x}' for a in (0xea0,0xea4,0xea8,0xeac)}
        if eac&(1<<27) or x==0x132 or y==0x36 or not 0xe6<x<0x11a or min(y,0x400-y)>=0x1a:
            raise RuntimeError(f'RX IQK step 2 failed: {result}')
        w.mask(0xc14,0xffff,x|((y&63)<<10),4)
        w.mask(0xca0,0xf0000000,(y>>6)<<28,4)
        result.update(passed=True,x=x,y=y)
    finally:
        w.w(0xe28,0,4)
        for a,v in rf_saved.items():w.rf_write(a,v)
        for a in (1,2):rf_mask(a,1,0)
        w.rf_write(0xef,0)
        for a,v in saved.items():w.w(a,v,4)
        for a,v in mac.items():w.w(a,v)
        w.w(0xc50,0x50);w.w(0xc50,mac[0xc50])
        writes([(0xe30,0x01008c00),(0xe34,0x01008c00)])
        w.coex_write(0x38,grants)
        w.report['rx_iqk']=result
    return result
