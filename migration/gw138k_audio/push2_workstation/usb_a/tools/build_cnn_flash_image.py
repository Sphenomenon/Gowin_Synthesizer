#!/usr/bin/env python3
"""Build the non-audio CNN weight image consumed from external SPI Flash.

The input is the existing 16-bit ``cnn_ddr_blob.mem`` word table.  The output
contains a small self-describing header followed by the same words in the
little-endian byte order used by the UART loader and the DDR CRC checker.
No PCM or other audio samples are accepted or generated by this tool.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import struct
import zlib
from pathlib import Path

MAGIC = b"BPF1"
VERSION = 1
HEADER_BYTES = 32
DEFAULT_WORDS = 52239
DEFAULT_BASE = 0x00600000
FLASH_BYTES = 0x01000000


def load_words(path: Path) -> list[int]:
    words: list[int] = []
    for line_no, token in enumerate(path.read_text().split(), 1):
        try:
            value = int(token, 16)
        except ValueError as exc:
            raise SystemExit(f"{path}:{line_no}: invalid hex word {token!r}") from exc
        if not 0 <= value <= 0xFFFF:
            raise SystemExit(f"{path}:{line_no}: word exceeds 16 bits: {token!r}")
        words.append(value)
    return words


def build_image(words: list[int]) -> tuple[bytes, dict[str, int | str]]:
    if not 1 <= len(words) <= 65536 or any(not isinstance(w,int) or not 0<=w<=65535 for w in words):
        raise ValueError("model must have 1..65536 unsigned 16-bit words")
    payload = b"".join(struct.pack("<H", word) for word in words)
    crc = zlib.crc32(payload) & 0xFFFFFFFF
    header = struct.pack(
        "<4sHHIIIIQ",
        MAGIC,
        VERSION,
        HEADER_BYTES,
        len(payload),
        crc,
        len(words),
        0,
        0,
    )
    assert len(header) == HEADER_BYTES
    manifest: dict[str, int | str] = {
        "magic": MAGIC.decode("ascii"),
        "version": VERSION,
        "header_bytes": HEADER_BYTES,
        "word_count": len(words),
        "payload_bytes": len(payload),
        "payload_crc32": f"{crc:08X}",
        "flash_image_bytes": len(header) + len(payload),
        "payload_byte_order": "little-endian 16-bit words",
        "contains_pcm": False,
    }
    return header + payload, manifest


def validate_image(image: bytes, expected_words: int = DEFAULT_WORDS) -> dict:
    if len(image)<HEADER_BYTES:
        raise ValueError("truncated model header")
    magic,version,header_bytes,payload_bytes,crc,words,flags,reserved=struct.unpack("<4sHHIIIIQ",image[:32])
    if (magic,version,header_bytes)!=(MAGIC,VERSION,HEADER_BYTES) or flags or reserved:
        raise ValueError("unsupported model header/version/flags")
    if words!=expected_words or payload_bytes!=words*2 or len(image)!=HEADER_BYTES+payload_bytes:
        raise ValueError("model ABI or image length mismatch")
    if zlib.crc32(image[HEADER_BYTES:])&0xffffffff!=crc:
        raise ValueError("model payload CRC mismatch")
    return dict(word_count=words,payload_bytes=payload_bytes,payload_crc32=f"{crc:08X}")


def pack_flash(bitstream: bytes, image: bytes, base: int = DEFAULT_BASE,
               capacity: int = FLASH_BYTES) -> tuple[bytes, dict]:
    model=validate_image(image)
    if base<DEFAULT_BASE or base%65536 or capacity<1 or capacity>FLASH_BYTES:
        raise ValueError("unsupported/un-aligned Flash partition/capacity")
    if not bitstream or len(bitstream)>base:
        raise ValueError("FPGA bitstream overlaps CNN model partition")
    if base+len(image)>capacity:
        raise ValueError("CNN image exceeds Flash capacity")
    bundle=bitstream+b"\xff"*(base-len(bitstream))+image
    return bundle,dict(**model,flash_capacity_bytes=capacity,flash_model_base=base,
                       model_image_bytes=len(image),bitstream_bytes=len(bitstream),
                       boot_image_bytes=len(bundle),model_image_sha256=hashlib.sha256(image).hexdigest(),
                       contains_pcm=False)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--mem", type=Path, required=True,
                        help="16-bit hex word table, normally cnn_ddr_blob.mem")
    parser.add_argument("--out", type=Path, required=True,
                        help="raw model image to program into the external Flash")
    parser.add_argument("--manifest", type=Path,
                        help="optional JSON manifest written beside the image")
    parser.add_argument("--base-address", type=lambda value: int(value, 0),
                        default=DEFAULT_BASE)
    parser.add_argument("--expected-words", type=int, default=DEFAULT_WORDS)
    parser.add_argument("--bitstream-bin",type=Path,help="optional Gowin raw bitstream binary")
    parser.add_argument("--bundle",type=Path,help="combined boot binary; required with --bitstream-bin")
    args = parser.parse_args()
    if bool(args.bitstream_bin)!=bool(args.bundle):
        parser.error("--bitstream-bin and --bundle must be supplied together")

    words = load_words(args.mem)
    if len(words) != args.expected_words:
        raise SystemExit(
            f"refusing truncated/extended model: expected {args.expected_words} words, "
            f"found {len(words)}"
        )
    image, manifest = build_image(words)
    if args.base_address<DEFAULT_BASE or args.base_address%65536 or args.base_address+len(image)>FLASH_BYTES:
        parser.error("model partition must be 64-KiB aligned, >=0x600000, inside 16 MiB")
    manifest["flash_base_address"] = args.base_address
    manifest["payload_address"] = args.base_address + HEADER_BYTES
    manifest["source_mem"] = str(args.mem)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_bytes(image)
    manifest_path = args.manifest or args.out.with_suffix(args.out.suffix + ".json")
    manifest_path.write_text(json.dumps(manifest, indent=2) + "\n")
    if args.bitstream_bin:
        try:bundle,bundle_manifest=pack_flash(args.bitstream_bin.read_bytes(),image,args.base_address)
        except ValueError as exc:parser.error(str(exc))
        args.bundle.parent.mkdir(parents=True,exist_ok=True)
        args.bundle.write_bytes(bundle)
        args.bundle.with_suffix(args.bundle.suffix+".json").write_text(json.dumps(bundle_manifest,indent=2)+"\n")
    print(json.dumps(manifest, indent=2))


if __name__ == "__main__":
    main()
