#!/usr/bin/env python3
"""Generate the synthesizer's 1024-sample, signed Q1.31 sine ROM.

Only the first quadrant (including both endpoints) is stored. The remaining
quadrants use reflection and sign inversion. This is a phase lookup table,
not recorded PCM: its pitch still comes from each voice's 32-bit DDS phase.
The bottom 22 phase bits are truncated; there is no interpolation or dither.
"""
import argparse
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "src" / "synth" / "synth_sine_rom.v"
QUARTER_SIZE = 256
PEAK = (1 << 31) - 1


def render():
    entries = "\n".join(
        f"            9'd{index}: magnitude = 32'h{math.floor(PEAK * math.sin(math.pi * index / (2 * QUARTER_SIZE)) + 0.5):08x};"
        for index in range(QUARTER_SIZE + 1)
    )
    return f"""// Generated by scripts/generate_sine_lut.py; do not edit the coefficients.
// 1024 points/period, 257-entry quarter-wave ROM, signed Q1.31 output.
// phase_index = DDS phase[31:22]. Lower bits are truncated, not interpolated.
// Symmetric peaks +/-0x7fffffff avoid a negative full-scale special case.
// Combinational lookup preserves the synth_voice sample-valid pipeline.
module synth_sine_rom (
    input wire [9:0] phase_index,
    output wire signed [31:0] sample_data
);
    wire [8:0] quarter_index = phase_index[8]
        ? 9'd256 - {{1'b0,phase_index[7:0]}}
        : {{1'b0,phase_index[7:0]}};
    reg [31:0] magnitude;
    always @* begin
        case (quarter_index)
{entries}
            default: magnitude = 32'd0;
        endcase
    end
    assign sample_data = phase_index[9] ? -$signed(magnitude) : $signed(magnitude);
endmodule
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="check generated RTL without rewriting it")
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != expected:
            raise SystemExit("Sine ROM is stale; run scripts/generate_sine_lut.py")
        print("PASS sine ROM coefficients (1024 points/period, signed Q1.31)")
    else:
        OUTPUT.write_text(expected, encoding="utf-8", newline="\n")
        print(OUTPUT)


if __name__ == "__main__":
    main()
