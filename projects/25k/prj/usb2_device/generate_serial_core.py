#!/usr/bin/env python3
"""Reproduce USB2 explicit-RX/TX CDC adaptation without changing USB1/vendor."""
from pathlib import Path
import hashlib
import json
import re

ROOT = Path(__file__).resolve().parent
VENDOR = ROOT.parent / "vendor/fpga_usb_device"
PINNED = {
    "RTL/usbfs_core/usbfs_core_top.v": "fbdd03c0231e00c088414096d33520bad83d2c4b808a2dedb3154e6f29cd4960",
    "RTL/usb_class/usb_serial_top.v": "cf631416c4148ecab8a713ff3d08c62b1b346ba19353505addd0bba73962f7e3",
}
FILTER_HASH = "89276d66a3044e60b627f7ba04cdcd09568cdfa5543d47a7f13a45344e39c552"
MANIFEST_HASH = "e140f9630036b21de2642454e785ff36d9343996450bc6064dc7d78820cd379f"

def checked(path, expected):
    raw = path.read_bytes()
    if hashlib.sha256(raw).hexdigest() != expected:
        raise SystemExit(f"Pinned input changed; review before regenerating: {path}")
    return raw.decode().replace("\r\n", "\n")

def once(text, old, new):
    if text.count(old) != 1:
        raise SystemExit(f"Expected one adaptation location: {old!r}")
    return text.replace(old, new)

# Check all unmodified protocol/class files as well as the two adapted tops.
manifest = json.loads(checked(VENDOR / "SOURCE.json", MANIFEST_HASH))
for entry in manifest["files"]:
    checked(VENDOR / entry["path"], entry["sha256"])
core = checked(VENDOR / "RTL/usbfs_core/usbfs_core_top.v", PINNED["RTL/usbfs_core/usbfs_core_top.v"])
cdc = checked(VENDOR / "RTL/usb_class/usb_serial_top.v", PINNED["RTL/usb_class/usb_serial_top.v"])
address_filter = checked(ROOT.parent / "usb1_device/rtl/usb1_address_filter.v", FILTER_HASH)

bridge = """// Address selection is identical to the verified USB1 bridge.
wire selected_byte_en, selected_fin, selected_okay;
usb2_address_filter u_address_filter (
    .clk(clk), .rstn(usb_rstn), .rp_pid(rp_pid), .rp_addr(rp_addr),
    .rp_byte_en(rp_byte_en), .rp_fin(rp_fin), .rp_okay(rp_okay),
    .setup_cmd(ep00_setup_cmd), .selected_byte_en(selected_byte_en),
    .selected_fin(selected_fin), .selected_okay(selected_okay)
);

"""
core = once(core, "usbfs_transaction #(\n", bridge + "usbfs_transaction #(\n")
start = core.index(") u_usbfs_transaction (")
end = core.index("\n);", start)
transaction = core[start:end]
for old, new in [("rp_byte_en", "selected_byte_en"), ("rp_fin", "selected_fin"),
                 ("rp_okay", "selected_okay")]:
    transaction = once(transaction, "( " + old, "( " + new)
core = core[:start] + transaction + core[end:]

pads = """    inout              usb_dp,        // USB D+
    inout              usb_dn,        // USB D-"""
ports = """    output wire        usb_oe,        // active-high transmit enable
    output wire        dp_tx,
    output wire        dn_tx,
    input  wire        dp_rx,         // resolved bus state; include TX loopback
    input  wire        dn_rx,""".rstrip(",")
# Both old pad lines ended in commas before comments. Preserve the final comma
# because usb_rstn follows the new input ports.
ports += ","
core = once(core, pads, ports)
cdc = once(cdc, pads, ports)
for declaration in ["wire        usb_oe;\n", "wire        usb_dp_tx;\n", "wire        usb_dn_tx;\n"]:
    core = once(core, declaration, "")
for driver in ["assign usb_dp = usb_oe ? usb_dp_tx : 1'bz;\n",
               "assign usb_dn = usb_oe ? usb_dn_tx : 1'bz;\n"]:
    core = once(core, driver, "")
# Only exact Verilog identifiers are changed: submodule port names such as
# usb_dp_rx/usb_dp_tx and usb_dp_pull must retain their original names.
for old, new in [("usb_dp_tx", "dp_tx"), ("usb_dn_tx", "dn_tx")]:
    # Change connection expressions only; bitlevel's formal ports retain names.
    core = once(core, "( " + old, "( " + new)
for old, new in [("usb_dp", "dp_rx"), ("usb_dn", "dn_rx")]:
    core = re.sub(r"\b" + old + r"\b", new, core)
cdc = once(cdc, """    .usb_dp             ( usb_dp           ),
    .usb_dn             ( usb_dn           ),""", """    .usb_oe             ( usb_oe           ),
    .dp_tx              ( dp_tx            ),
    .dn_tx              ( dn_tx            ),
    .dp_rx              ( dp_rx            ),
    .dn_rx              ( dn_rx            ),""")
address_filter = once(address_filter, "module usb1_address_filter", "module usb2_address_filter")

if re.search(r"\b(?:usb_dp|usb_dn)\b", core + cdc):
    raise SystemExit("Unexpected direct-pad reference remains in adapted source")
header = """// GENERATED by ../generate_serial_core.py; regenerate rather than edit.
// Upstream WangXuan95/FPGA-USB-Device ebf0696f0b1dc604a4ed8eedee4c3eae1643e66f.
// LGPL-2.1, see ../../vendor/fpga_usb_device/LICENSE.
// Local changes: verified address filter plus explicit resolved RX / TX / OE.
// The packet/transaction/descriptors/FIFO/2s attach/SE0-reset logic is retained.
"""
out = ROOT / "generated"
out.mkdir(exist_ok=True)
for name, text in [("usbfs_core_top.v", core), ("usb_serial_top.v", cdc),
                   ("usb2_address_filter.v", address_filter)]:
    target = out / name
    target.write_text(header + text)
    print(target)
