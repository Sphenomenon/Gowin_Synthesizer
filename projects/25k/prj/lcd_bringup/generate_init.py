#!/usr/bin/env python3
"""Generate a path-independent synthesizable ROM and an SPI scoreboard fixture."""
from pathlib import Path
import argparse

ROOT = Path(__file__).resolve().parent


def entries():
    result = []
    for number, line in enumerate((ROOT / 'nv3007_279_init.txt').read_text().splitlines(), 1):
        fields = line.split('#', 1)[0].split()
        if not fields:
            continue
        if fields[0] == '@delay':
            value = int(fields[1])
            assert 0 < value <= 65535, number
            result.append((2, value))
        else:
            for index, field in enumerate(fields):
                value = int(field, 16)
                assert 0 <= value <= 255, number
                result.append((int(index != 0), value))
    assert len(result) < 511
    return result


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    tokens = entries()
    header = '''`timescale 1ns/1ps
// Generated by generate_init.py; edit nv3007_279_init.txt, not this file.
// Candidate table adapted from Arduino_GFX; see THIRD_PARTY_LICENSE.txt.
module lcd_init_rom (
    input wire [8:0] index,
    output wire [1:0] kind,
    output wire [15:0] value
);
    function [17:0] lookup;
        input [8:0] address;
        begin
        case (address)
'''
    rows = ''.join(f"            9'd{i}: lookup={{2'd{k},16'h{v:04x}}};\n"
                   for i, (k, v) in enumerate(tokens))
    rtl = header + rows + "            default: lookup={2'd3,16'h0000};\n        endcase\n        end\n    endfunction\n    assign {kind,value}=lookup(index);\nendmodule\n"
    expected = ''.join(f'{((kind << 16) | value):05x}\n' for kind, value in tokens)
    for path, content in [(ROOT / 'src/lcd_init_rom.v', rtl),
                          (ROOT / 'sim/init_expected.mem', expected)]:
        if args.check:
            assert path.read_text() == content, f'Stale generated file: {path}'
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    print(f'Candidate ROM: {len(tokens)} tokens, '
          f'{sum(k < 2 for k, _ in tokens)} SPI bytes, '
          f'{sum(k == 0 for k, _ in tokens)} commands, '
          f'{sum(v for k, v in tokens if k == 2)} ms delay')


if __name__ == '__main__':
    main()
