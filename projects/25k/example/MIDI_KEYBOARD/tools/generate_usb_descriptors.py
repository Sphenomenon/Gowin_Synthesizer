#!/usr/bin/env python3
"""Generate self-contained FS/HS USB-MIDI + vendor descriptors and manifest.

Default FB9A:FB9B are inherited local laboratory identifiers, NOT an allocated
product VID/PID. Supply authorized --vid/--pid for distribution.
"""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def u16(value):
    return [value & 255, value >> 8]


def string(value):
    encoded = value.encode("utf-16le")
    return [len(encoded) + 2, 3, *encoded]


def configuration(high_speed, descriptor_type=2):
    packet = u16(512 if high_speed else 64)
    # Audio 1.0 AC header names MIDIStreaming interface 1. The MIDI header
    # wTotalLength spans the MIDI class block, including its endpoint records,
    # matching the interoperable USB-MIDI 1.0 descriptor layout (65 bytes).
    ac = [9, 4, 0, 0, 0, 1, 1, 0, 0, 9, 0x24, 1, 0, 1, 9, 0, 1, 1]
    midi_cs = [7, 0x24, 1, 0, 1, 0, 0]
    midi_cs += [6, 0x24, 2, 1, 1, 0]  # Embedded IN 1: host OUT
    midi_cs += [6, 0x24, 2, 2, 4, 0]  # External IN 4: local keyboard
    midi_cs += [9, 0x24, 3, 1, 3, 1, 4, 1, 0]  # Embedded OUT 3 <- 4
    midi_cs += [9, 0x24, 3, 2, 2, 1, 1, 1, 0]  # External OUT 2 <- 1
    midi_cs[5:7] = u16(len(midi_cs) + 2 * (9 + 5))
    midi = [9, 4, 1, 0, 2, 1, 3, 0, 0] + midi_cs
    midi += [9, 5, 0x01, 2, *packet, 0, 0, 0, 5, 0x25, 1, 1, 1]
    midi += [9, 5, 0x81, 2, *packet, 0, 0, 0, 5, 0x25, 1, 1, 3]
    screen = [9, 4, 2, 0, 2, 0xff, 0, 0, 0]
    screen += [7, 5, 0x02, 2, *packet, 0, 7, 5, 0x82, 2, *packet, 0]
    body = ac + midi + screen
    return [9, descriptor_type, *u16(9 + len(body)), 3, 1, 0, 0x80, 50] + body


def build(vid, pid):
    device = [18, 1, 0, 2, 0, 0, 0, 64, *u16(vid), *u16(pid), 0, 1, 1, 2, 3, 1]
    qualifier = [10, 6, 0, 2, 0, 0, 0, 64, 1, 0]
    common = {0x0100: device, 0x0600: qualifier, 0x0300: [4, 3, 9, 4],
              0x0301: string("GW25K Lab"), 0x0302: string("GW25K MIDI Screen"),
              0x0303: string("GW25K-MIDI-0001")}
    result = {}
    for hs in (False, True):
        result[hs] = {**common, 0x0200: configuration(hs), 0x0700: configuration(not hs, 7)}
    return result


def validate(descriptors):
    for hs, mapping in descriptors.items():
        config = mapping[0x0200]
        assert len(config) == int.from_bytes(bytes(config[2:4]), "little")
        assert config[4] == 3 and mapping[0x0100][7] == 64
        position, interfaces, endpoints, jack_ids, sources = 0, [], [], set(), []
        current_interface = None
        while position < len(config):
            length, kind = config[position:position + 2]
            record = config[position:position + length]
            assert length >= 2 and len(record) == length
            if kind == 4:
                current_interface = record[2]
                interfaces.append(record[2])
            if kind == 5:
                assert record[3] == 2
                assert int.from_bytes(bytes(record[4:6]), "little") == (512 if hs else 64)
                endpoints.append(record[2])
            if kind == 0x24 and current_interface == 1 and record[2] in (2, 3):
                jack_ids.add(record[4])
                if record[2] == 3:
                    sources.append(record[6])
            position += length
        assert interfaces == [0, 1, 2]
        assert endpoints == [0x01, 0x81, 0x02, 0x82]
        assert jack_ids == {1, 2, 3, 4} and set(sources) <= jack_ids
        assert mapping[0x0700][1] == 7
        for selector, record in mapping.items():
            if selector >> 8 == 3:
                assert record[0] == len(record) and len(record) % 2 == 0


def emit_rom(descriptors):
    lines = ["// Generated by tools/generate_usb_descriptors.py; do not hand edit.",
             "// Default VID/PID are local laboratory values, not a product allocation.",
             "module midi_usb_desc_rom(input wire hs,input wire[15:0]selector,",
             " input wire[15:0]offset,output reg[7:0]data,",
             " output reg[15:0]length,output reg supported);",
             "always @* begin data=0;length=0;supported=1;case(selector)"]
    for selector in sorted(descriptors[False]):
        fs, hs = descriptors[False][selector], descriptors[True][selector]
        assert len(fs) == len(hs)
        lines += [f"16'h{selector:04x}:begin length=16'd{len(fs)};case(offset)"]
        for index, (f, h) in enumerate(zip(fs, hs)):
            value = f"8'h{f:02x}" if f == h else f"(hs?8'h{h:02x}:8'h{f:02x})"
            lines.append(f"16'd{index}:data={value};")
        lines += ["default:data=0;endcase end"]
    lines += ["default:begin supported=0;length=0;data=0;end", "endcase end", "endmodule", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--vid", type=lambda s: int(s, 0), default=0xfb9a)
    parser.add_argument("--pid", type=lambda s: int(s, 0), default=0xfb9b)
    parser.add_argument("--check", action="store_true", help="Verify generated files are current")
    args = parser.parse_args()
    if not 0 < args.vid <= 65535 or not 0 < args.pid <= 65535:
        parser.error("VID and PID must be nonzero 16-bit values")
    descriptors = build(args.vid, args.pid)
    validate(descriptors)
    rom = emit_rom(descriptors)
    manifest = {"schema_version": 1, "vid": f"0x{args.vid:04x}", "pid": f"0x{args.pid:04x}",
                "identity_usage": "local_laboratory_unallocated", "usb": "2.0", "ep0_packet": 64,
                "descriptor_rom_sha256": hashlib.sha256(rom.encode()).hexdigest(),
                "descriptors": {"high_speed" if hs else "full_speed": {
                    f"0x{sel:04x}": {"length": len(blob), "hex": bytes(blob).hex()}
                    for sel, blob in sorted(mapping.items())} for hs, mapping in descriptors.items()}}
    outputs = {ROOT / "rtl/usb_board/generated/usb_composite_desc_rom.v": rom,
               ROOT / "config/usb_descriptors.json": json.dumps(manifest, indent=2) + "\n"}
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f"Generated file is stale: {path}")
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    print(f"PASS USB descriptors: three interfaces, MIDI jacks, four bulk endpoints, FS/HS, {len(descriptors[True][0x0200])}-byte configuration")


if __name__ == "__main__":
    main()
