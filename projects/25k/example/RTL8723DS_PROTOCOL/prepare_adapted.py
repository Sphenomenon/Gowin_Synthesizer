"""Generate minimal Gowin storage adaptations without modifying vendor RTL."""
from pathlib import Path
import argparse
import hashlib
import json

project = Path(__file__).resolve().parent
vendor = project / 'vendor' / 'rtl8723ds_ble'
arguments = argparse.ArgumentParser()
arguments.add_argument('--output', type=Path, default=project / 'generated' / 'rtl')
output = arguments.parse_args().output.resolve()
output.mkdir(parents=True, exist_ok=True)
manifest = json.loads((vendor/'MANIFEST.json').read_text())['files']

def original(name):
    data = (vendor/'rtl'/name).read_bytes()
    expected = manifest['rtl/' + name]
    if len(data) != expected['bytes'] or hashlib.sha256(data).hexdigest() != expected['sha256']:
        raise SystemExit('Refuse to adapt changed vendor source: ' + name)
    return data.decode()

def replace(text, before, after):
    if text.count(before) != 1:
        raise SystemExit('Adaptation anchor changed or is ambiguous: ' + before)
    return text.replace(before, after)

h5 = (project/'adaptations/bt_h5_transport.v').read_text()
h5 = replace(h5,
    '    reg [7:0] pending_ram [0:MAX_PAYLOAD-1];',
    '    (* ram_style = "block" *) reg [7:0] pending_ram [0:MAX_PAYLOAD-1];')
h5 = replace(h5,
    'if (wire_host) raw_byte = pending_ram[wire_index-4];',
    'if (wire_host) raw_byte = pending_data;')
h5 = replace(h5,
    '                pending_ram[copy_index] <= tx_payload_data;\n', '')
memory = '''    // Gowin adaptation: infer a synchronous-read payload block RAM.
    // There is no array reset. No payload is observed until host_copy ends.
    // wire_index advances only when UART accepts the preceding character;
    // its 11 bit times give pending_data a full cycle to prefetch each byte.
    wire [8:0] pending_read_addr = wire_index - 9'd4;
    reg [7:0] pending_data;
    always @(posedge clk) begin
        if (resetn && enable && host_copy && !host_copy_wait)
            pending_ram[copy_index] <= tx_payload_data;
        pending_data <= pending_ram[pending_read_addr];
    end

'''
h5 = replace(h5, '    always @* begin\n', memory + '    always @* begin\n')

gatt = (project/'adaptations/bt_gatt.v').read_text()
# ATT MTU=23 + four ACL + four L2CAP bytes <=31. Keep both response
# slots and the exact scheduling; only remove unreachable spare storage.
for before, after in [
    ('reg [7:0] response [0:159];', 'reg [7:0] response [0:63];'),
    ('reg [7:0] active_tx [0:79];', 'reg [7:0] active_tx [0:31];'),
    ('tx_payload_addr < 80 ?', 'tx_payload_addr < 32 ?'),
    ('(read_slot ? 80 : 0)+tx_copy_index', '(read_slot ? 32 : 0)+tx_copy_index'),
]:
    gatt = replace(gatt, before, after)

if gatt.count('response_base=write_slot ? 80 : 0;') != 2:
    raise SystemExit('Unexpected business response-slot anchors')
gatt = gatt.replace('response_base=write_slot ? 80 : 0;', 'response_base=write_slot ? 32 : 0;')

for name, text in [('bt_h5_transport.v', h5), ('bt_gatt.v', gatt)]:
    (output/name).write_text('// Generated by prepare_adapted.py; vendor remains unchanged.\n' + text)
print('Gowin storage adaptations: H5 pending payload synchronous RAM; GATT 2x32-byte slots +32-byte active TX')
