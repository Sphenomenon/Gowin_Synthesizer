#!/usr/bin/env python3
"""Reproduce the minimal address-selection bridge; never edit vendor sources."""
from pathlib import Path
import hashlib
import json

root = Path(__file__).resolve().parent
vendor = root / 'vendor/fpga_usb_device'
for entry in json.loads((vendor/'SOURCE.json').read_text())['files']:
    if hashlib.sha256((vendor/entry['path']).read_bytes()).hexdigest() != entry['sha256']:
        raise SystemExit('Pinned upstream file hash changed: '+entry['path'])
source = vendor / 'RTL/usbfs_core/usbfs_core_top.v'
raw = source.read_bytes()
expected = 'fbdd03c0231e00c088414096d33520bad83d2c4b808a2dedb3154e6f29cd4960'
if hashlib.sha256(raw).hexdigest() != expected:
    raise SystemExit('Pinned upstream core hash changed; review adaptation before regeneration.')
text = raw.decode().replace('\r\n', '\n')
declaration = '''// Local adaptation: address filter between original RX packet and transaction.
wire selected_byte_en, selected_fin, selected_okay;
usb1_address_filter u_address_filter (
    .clk(clk), .rstn(usb_rstn), .rp_pid(rp_pid), .rp_addr(rp_addr),
    .rp_byte_en(rp_byte_en), .rp_fin(rp_fin), .rp_okay(rp_okay),
    .setup_cmd(ep00_setup_cmd), .selected_byte_en(selected_byte_en),
    .selected_fin(selected_fin), .selected_okay(selected_okay)
);

'''
marker = 'usbfs_transaction #(\n'
if text.count(marker) != 1:
    raise SystemExit('Expected one transaction instance.')
text = text.replace(marker, declaration + marker)
start = text.index(') u_usbfs_transaction (')
end = text.index('\n);', start)
bridge = text[start:end]
for original, selected in [('rp_byte_en', 'selected_byte_en'),
                           ('rp_fin', 'selected_fin'), ('rp_okay', 'selected_okay')]:
    old = '( ' + original
    if bridge.count(old) != 1:
        raise SystemExit('Unexpected transaction connection: ' + original)
    bridge = bridge.replace(old, '( ' + selected)
text = text[:start] + bridge + text[end:]
header = '''// GENERATED by ../generate_core.py from unmodified LGPL-2.1 upstream source.
// Upstream: WangXuan95/FPGA-USB-Device, commit ebf0696f0b1dc604a4ed8eedee4c3eae1643e66f.
// Local change: insert usb1_address_filter; all other core behavior is preserved.
// License: ../vendor/fpga_usb_device/LICENSE. Regenerate rather than edit.
'''
destination = root / 'generated/usbfs_core_top.v'
destination.parent.mkdir(exist_ok=True)
destination.write_text(header + text)
print(destination)
