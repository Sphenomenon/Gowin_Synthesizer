def simulation(output: Path) -> dict:
    reference = output / "feedback_capture_reference.v"
    old = FIXTURE.read_text()
    assert old.count("module feedback_capture #(") == 1
    reference.write_text(old.replace("module feedback_capture #(", "module feedback_capture_reference #("))
    bench = output / "tb.sv"
    bench.write_text(BENCH)
    sources = {"complete_capture_and_function": SOURCE}
    new = SOURCE.read_text()
    for name, (before, after) in MUTATIONS.items():
        assert new.count(before) == 1, (name, "mutation anchor drift")
        path = output / f"{name}.v"
        path.write_text(new.replace(before, after))
        sources[name] = path
    cases = {}
    for registered in (0, 1):
        for name, source in sources.items():
            case = f"input{registered}-{name}"
            binary = output / f"{case}.vvp"
            argv = ["iverilog", "-g2012", "-s", "tb", f"-Ptb.INPUT_REGISTERED={registered}",
                    "-o", str(binary), str(bench), str(source), str(reference)]
            compile_run = subprocess.run(argv, capture_output=True, text=True, timeout=60)
            (output / f"{case}-compile.log").write_text(compile_run.stdout + compile_run.stderr)
            assert compile_run.returncode == 0, (case, "compile failed", compile_run.stderr)
            start = time.monotonic()
            run = subprocess.run(["vvp", str(binary)], capture_output=True, text=True, timeout=300)
            log = output / f"{case}.log"
            log.write_text(run.stdout + run.stderr)
            expected_pass = name == "complete_capture_and_function"
            assert (run.returncode == 0) == expected_pass, (case, log.read_text()[-3000:])
            metrics = None
            if expected_pass:
                line = next(line for line in run.stdout.splitlines() if line.startswith("PASS "))
                metrics = {k: int(v) for k, v in re.findall(r"(\w+)=(\d+)", line)}
            else:
                assert "SMOOTH_MISMATCH" in run.stdout, (case, "negative control lacked intended arithmetic mismatch")
            cases[case] = {
                "input_registered": registered, "compile_argv": argv,
                "returncode": run.returncode, "expected_success": expected_pass,
                "seconds": time.monotonic() - start, "metrics": metrics,
                "source_sha256": sha(source), "log_sha256": sha(log),
            }
            print(f"{case}: {'PASS' if expected_pass else 'EXPECTED_ARITHMETIC_FAILURE'}", flush=True)
    return {
        "cases": cases,
        "comparison": "Both complete modules, all declared persistent scalar/vector state except the unused loop integer, six poles, all public outputs, every written RAM word, all 1024 RAM words at each publication and end; source/render posedge+1 checks.",
        "clocks": "source period 10ns, render period 14ns; simultaneous reset assertion contract retained",
        "coverage": "Default 512 samples/8192 timeout, true timeout, smooth/phase/silence starts, prolonged renderer hold and skipped samples, 512-word reads before release, metadata changes, three reset cycles, valid gaps and X/Z PCM.",
        "limit": "Selected dual-clock temporal simulation and universal function argument; no whole-module temporal/CDC formal or hardware claim.",
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", required=True, type=Path)
    args = parser.parse_args()
    identity = source_guard()
    for executable in ("iverilog", "vvp"):
        assert shutil.which(executable), f"missing {executable}"
    import z3  # Fail before creating evidence if the public proof dependency is absent.
    output = args.output.resolve()
    output.mkdir(parents=True, exist_ok=False)
    proof = independent_proof(output)
    (output / "independent-proof.json").write_text(json.dumps(proof, indent=2) + "\n")
    results = simulation(output)
    assert source_guard() == identity, "source inputs changed during verification"
    record = {
        "schema": 1, "status": "passed", "stage": "maintained_feedback_smooth_csa_regression",
        "identity": identity, "runner_sha256": sha(Path(__file__)),
        "proof": proof, "simulation": results,
        "routed_timing_verified": False, "resource_improvement_measured": False, "hardware_tested": False,
        "artifacts_sha256": {p.name: sha(p) for p in sorted(output.iterdir()) if p.is_file() and p.suffix != ".vvp"},
    }
    (output / "verification.json").write_text(json.dumps(record, indent=2) + "\n")
    print(json.dumps({"status": "passed", "verification": str(output / "verification.json"),
                      "verification_sha256": sha(output / "verification.json")}, indent=2))


if __name__ == "__main__":
    main()
