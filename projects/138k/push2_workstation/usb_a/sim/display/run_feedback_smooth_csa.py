#!/usr/bin/env python3
"""Recheck the exact smooth CSA rewrite against a versioned complete old module.

Requires Python z3-solver, iverilog and vvp. Outputs are deliberately separate
from source and existing evidence: --output must name a new directory. No private
cache, prepared workstation, board, or frozen baseline is an input.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import re
import shutil
import subprocess
import time

ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / "rtl/display_data/feedback_capture.v"
FIXTURE = ROOT / "sim/fixtures/feedback_capture_before_smooth_csa.v"
BASE_SHA = "62195a1777f8308f0e20687e6dcae14af932e65eac0cf6ca814b6e40d294bb56"
SOURCE_SHA = "6b09b616d061a2d6fb8defd08d8be2889e70fca93e0d05a243b42887a3eddab9"
OLD_FUNCTION_SHA = "f94f22f1b875a1bf57252a14ac7c474c736658483350a402f04200616fb73694"
NEW_FUNCTION_SHA = "0904354561c364a4722eac08493db7e03e3ce8fe70b2ccf189bd0accf487dff8"
FUNCTION = rb"        function signed \[31:0\] smooth\(input signed \[31:0\] value,old_value\);.*?        endfunction"
MUTATIONS = {
    "missing_33bit_overflow": ("32'hf0000000 : 32'd0", "32'd0 : 32'd0"),
    "bad_rounding": ("+7'd17;", "+7'd16;"),
    "lost_carry_operand": ("sum2=sum1^carry1^round_carry;", "sum2=sum1^carry1;"),
}


def sha_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def sha(path: Path) -> str:
    return sha_bytes(path.read_bytes())


def source_guard() -> dict:
    old, new = FIXTURE.read_bytes(), SOURCE.read_bytes()
    assert sha_bytes(old) == BASE_SHA, "exact pre-change complete module drifted"
    assert sha_bytes(new) == SOURCE_SHA, "approved maintained complete module drifted"
    a, b = re.search(FUNCTION, old, re.S), re.search(FUNCTION, new, re.S)
    assert a and b, "smooth function anchors missing"
    assert sha_bytes(a.group()) == OLD_FUNCTION_SHA
    assert sha_bytes(b.group()) == NEW_FUNCTION_SHA
    assert new[:b.start()] + a.group() + new[b.end():] == old, "change escaped smooth function"
    return {
        "source": str(SOURCE), "source_sha256": sha_bytes(new),
        "fixture": str(FIXTURE), "fixture_sha256": sha_bytes(old),
        "old_function_sha256": OLD_FUNCTION_SHA, "new_function_sha256": NEW_FUNCTION_SHA,
        "outside_function_byte_identical": True,
        "state_ports_parameters_clocks_and_latency_changed": False,
    }


def independent_proof(output: Path) -> dict:
    # This model is independently translated, rather than generated by the CSA
    # source. The exact old/new bodies are separately bound by source_guard().
    import z3

    value, old = z3.BitVecs("value old", 32)
    delta = z3.SignExt(1, value) - z3.SignExt(1, old)
    original = z3.Extract(31, 0, z3.SignExt(1, old) + ((delta + z3.BitVecVal(16, 33)) >> 5))
    upper = z3.SignExt(5, z3.Extract(31, 5, value))
    complement = ~z3.SignExt(5, z3.Extract(31, 5, old))
    sum1 = old ^ upper ^ complement
    carry1 = ((old & upper) | (old & complement) | (upper & complement)) << 1

    def model(rounding: int = 17, overflow: bool = True, lose_operand: bool = False):
        low = (z3.ZeroExt(2, z3.Extract(4, 0, value)) +
               z3.ZeroExt(2, ~z3.Extract(4, 0, old)) + z3.BitVecVal(rounding, 7))
        rounding_carry = z3.ZeroExt(30, z3.Extract(6, 5, low))
        correction = z3.If(z3.And(z3.Extract(31, 5, value) == 0x3ffffff,
                                  z3.Extract(31, 5, old) == 0x4000000,
                                  z3.Extract(6, 5, low) == 2),
                           z3.BitVecVal(0xf0000000, 32), z3.BitVecVal(0, 32))
        if not overflow:
            correction = z3.BitVecVal(0, 32)
        sum2 = sum1 ^ carry1 if lose_operand else sum1 ^ carry1 ^ rounding_carry
        carry2 = ((sum1 & carry1) | (sum1 & rounding_carry) | (carry1 & rounding_carry)) << 1
        sum3 = sum2 ^ carry2 ^ correction
        carry3 = ((sum2 & carry2) | (sum2 & correction) | (carry2 & correction)) << 1
        return sum3 + carry3

    def solve(name, formula, expected, counterexample=False):
        solver = z3.Solver()
        solver.set(timeout=120000)
        solver.add(formula)
        (output / f"{name}.smt2").write_text(solver.to_smt2())
        start = time.monotonic()
        result = str(solver.check())
        assert result == expected, (name, result)
        record = {"result": result, "seconds": time.monotonic() - start}
        if counterexample:
            witness = solver.model()
            record["counterexample"] = {
                "value": f"{witness.eval(value, model_completion=True).as_long():08x}",
                "old_value": f"{witness.eval(old, model_completion=True).as_long():08x}",
            }
        return record

    binary = solve("binary-equivalence", original != model(), "unsat")
    binary.update(arbitrary_input_bits=64, reachable_state_assumptions=False)

    # IEEE operator argument for all X/Z locations, independent of binary SMT:
    # X/Z in either low operand makes the whole seven-bit low_sum arithmetic X.
    # XOR cannot resolve unknowns, so known(sum3) is a subset of
    # known(old ^ upper ^ complement) & known(rounding_carry). If any input
    # bit is unknown this upper bound has an unknown bit. Final arithmetic +
    # yields all X, just as the original 33-bit subtraction/addition does.
    vk, ok = z3.BitVecs("value_known_mask old_known_mask", 32)
    all_known = z3.BitVecVal(0xffffffff, 32)
    upper_known = z3.SignExt(5, z3.Extract(31, 5, vk))
    complement_known = z3.SignExt(5, z3.Extract(31, 5, ok))
    low_known = z3.And(z3.Extract(4, 0, vk) == 31, z3.Extract(4, 0, ok) == 31)
    round_known = z3.If(low_known, all_known, z3.BitVecVal(0xfffffffc, 32))
    bound = ok & upper_known & complement_known & round_known
    four_state = solve("four-state-known-mask", z3.And(z3.Or(vk != all_known, ok != all_known),
                                                       bound == all_known), "unsat")
    four_state.update(arbitrary_known_mask_bits=64, method="sound IEEE operator known-mask upper bound")
    controls = {
        "missing_33bit_overflow": model(overflow=False),
        "bad_rounding": model(rounding=16),
        "lost_carry_operand": model(lose_operand=True),
    }
    negative = {name: solve(f"negative-{name}", original != expr, "sat", True)
                for name, expr in controls.items()}
    critical = z3.simplify(z3.substitute(original, (value, z3.BitVecVal(0x7fffffff, 32)),
                                       (old, z3.BitVecVal(0x80000000, 32)))).as_long()
    assert critical == 0x78000000
    return {
        "binary": binary, "four_state": four_state, "negative_controls": negative,
        "critical_original_33bit_wrap": {"value": "7fffffff", "old_value": "80000000", "result": f"{critical:08x}"},
        "scope": "Exact source hashes bind independently hand-translated arithmetic and IEEE operator argument. No source-language frontend or whole temporal formal equivalence claim.",
        "z3_version": z3.get_version_string(),
    }


