#ifndef GW138K_RECORDING_SERVICE_H
#define GW138K_RECORDING_SERVICE_H
#include <stdint.h>
#include <stddef.h>
#define A138_RECORD_BASE UINT32_C(0xf8040000)
enum {
    A138_REC_ID=0x00,A138_REC_CAPS=0x04,A138_REC_COMMAND=0x08,A138_REC_STATUS=0x0c,
    A138_REC_STAGE_ID_LOW=0x10,A138_REC_STAGE_ID_HIGH=0x14,A138_REC_LIMIT=0x18,
    A138_REC_OBJECT_LOW=0x1c,A138_REC_OBJECT_HIGH=0x20,A138_REC_RATE=0x24,
    A138_REC_EPOCH=0x28,A138_REC_FRAMES=0x2c,A138_REC_COMMITTED=0x30,
    A138_REC_OFFSET=0x40,A138_REC_LENGTH=0x44,A138_REC_DATA_STATUS=0x48,A138_REC_DATA0=0x4c
};
enum { A138_REC_CREATE=1,A138_REC_SEAL=2,A138_REC_CANCEL=3,A138_REC_CLEAR=4,
    A138_REC_ACQUIRE=5,A138_REC_RELEASE=6,A138_REC_DOWNLOAD=7,
    A138_REC_POP_HEAD=8,A138_REC_RELEASE_HEAD=9 };
typedef struct {
    void *context;
    int (*read)(void *,uint32_t,uint32_t *);
    int (*write)(void *,uint32_t,uint32_t);
} a138_record_bus;
typedef struct { uint64_t object_id;uint32_t state,failure,rate_hz,epoch,frames,committed; } a138_record_status;
typedef struct { uint32_t words[8];uint32_t bytes,last; } a138_record_head;
/* All functions are bounded, single-caller service operations. Callback zero
 * means transport failure; writes can have committed and MUST NOT auto-retry.
 * CREATE's bus callback needs a timeout above the 4-ms source-frame deadline.
 * The caller supplies a nonzero unique object ID; it is not generated by RTL.
 * CPU observer reset preserves capture and immutable objects, but releases and
 * drains download references. Resume requires a new reference and explicit
 * byte offset. Poll is advisory across separate bus reads: repeated ID reads
 * detect identity changes only; CAPTURE frames/committed can advance between
 * reads. Use READY for a stable immutable descriptor and POP_HEAD's atomic data
 * snapshot for bytes. A sticky PCM observation loss rejects later CREATE until
 * controller reset; CPU observer reset does not clear source health.
 * This API does not implement BLE formats, CRC or task IDs. */
a138_record_bus a138_record_mmio_bus(uintptr_t base);
int a138_record_probe(const a138_record_bus *bus);
int a138_record_create(const a138_record_bus *bus,uint64_t id,uint32_t frames);
int a138_record_command(const a138_record_bus *bus,uint32_t command);
int a138_record_poll(const a138_record_bus *bus,a138_record_status *status);
int a138_record_acquire(const a138_record_bus *bus,uint64_t id);
int a138_record_download(const a138_record_bus *bus,uint32_t offset,uint32_t length);
/* POP_HEAD is explicit. read_head only reads an already captured immutable
 * 32-byte window; it does not consume a backend beat or release the window. */
int a138_record_read_head(const a138_record_bus *bus,a138_record_head *head);
#endif
