#!/usr/bin/env python3
"""Generate the small official-logo ROM and shared 24-pixel glyph atlas.

The original logo is never rewritten. Supply the pinned Google Fonts Noto Sans
SC variable font; compilation consumes only the checked-in ROMs and header.
"""
from pathlib import Path
import argparse
import hashlib
import json

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'rtl/display_data/assets'
TITLE = "全国大学生嵌入式芯片与系统设计竞赛'2026 FPGA创新设计赛道 · 高云半导体"
PRINCIPLE = '创意发挥、规范设计、突破自我、快乐竞赛'
FONT_SHA256 = 'a3041811a78c361b1de50f953c805e0244951c21c5bd412f7232ef0d899af0da'
LOGO_SHA256 = 'aed6092164c0e0ef9eaf68931066147abc6e5466bbaaa6b46de60d2f15fe92ad'
PALETTE = [(255, 255, 255), (25, 74, 139), (40, 115, 174), (48, 171, 221)]
INK = (44, 52, 63)


def sha(data):
    return hashlib.sha256(data).hexdigest()


def generate(font_path):
    logo_path = ASSETS / 'contest_fpga_logo_original.png'
    assert sha(logo_path.read_bytes()) == LOGO_SHA256
    assert sha(font_path.read_bytes()) == FONT_SHA256
    logo = Image.open(logo_path).convert('RGBA')
    assert logo.size == (283, 80)
    white = Image.new('RGBA', logo.size, 'white')
    white.alpha_composite(logo)
    logo_rgb = white.convert('RGB')
    rgb_bytes = logo_rgb.tobytes()
    codes = [min(range(4), key=lambda k: sum((v - c) ** 2
                                           for v, c in zip(rgb_bytes[offset:offset + 3], PALETTE[k])))
             for offset in range(0, len(rgb_bytes), 3)]
    # 142 four-bit words per row. Low pair is the even pixel; the padded odd
    # pixel at x=283 is white and lies outside the displayed 283-pixel image.
    words = []
    for y in range(80):
        for x in range(0, 284, 2):
            even = codes[y * 283 + x]
            odd = codes[y * 283 + x + 1] if x + 1 < 283 else 0
            words.append(even | (odd << 2))
    characters = list(dict.fromkeys(' ' + TITLE + PRINCIPLE))
    assert len(characters) == 47 and len(TITLE) == 41 and len(PRINCIPLE) == 19
    font = ImageFont.truetype(str(font_path), 24)
    font.set_variation_by_axes([500])
    rows, glyphs = [], {}
    for character in characters:
        image = Image.new('L', (24, 24))
        ImageDraw.Draw(image).text((0, 21), character, font=font, fill=255, anchor='ls')
        image = image.point(lambda value: 255 if value >= 128 else 0)
        glyphs[character] = image
        for y in range(24):
            rows.append(sum((1 << (23 - x)) for x in range(24) if image.getpixel((x, y))))
    # Decode eight-pixel chunks rather than synthesizing division by 24.
    # The high six result bits select a fixed character; low two select its
    # eight-pixel third. Each chunk has one constant table entry.
    header = ['// Generated by tools/generate_workstation_contest_brand.py.']
    header += ['function automatic [7:0] brand_column(input [6:0] chunk);',
               '    begin case (chunk)']
    for chunk in range(123):
        header.append(f"        7'd{chunk}: brand_column = 8'd{(chunk // 3) * 4 + chunk % 3};")
    header += ["        default: brand_column = 8'd0;", '    endcase end', 'endfunction',
               'function automatic [5:0] brand_glyph(input line_id, input [5:0] column);',
               '    begin case ({line_id, column})']
    for line_id, line in enumerate([TITLE, PRINCIPLE]):
        for column, character in enumerate(line):
            header.append(f"        7'd{line_id * 64 + column}: brand_glyph = 6'd{characters.index(character)}; // U+{ord(character):04X}")
    header += ["        default: brand_glyph = 6'd0;", '    endcase end', 'endfunction',
               'function automatic [23:0] brand_palette(input [1:0] code);',
               '    begin case (code)']
    for i, rgb in enumerate(PALETTE):
        header.append(f"        2'd{i}: brand_palette = 24'h{rgb[0]:02X}{rgb[1]:02X}{rgb[2]:02X};")
    header += ["        default: brand_palette = 24'hFFFFFF;", '    endcase end', 'endfunction']
    layout = dict(schema=1, title=TITLE, principle=PRINCIPLE,
                  principle_source_designation='竞赛原则',
                  font=dict(name='Noto Sans SC', size_px=24, weight_axis=500,
                            baseline_px=21, threshold=128, sha256=FONT_SHA256),
                  logo=dict(original_sha256=LOGO_SHA256, x=64, y=24, width=283,
                            height=80, bits_per_pixel=2, pixels_per_word=2,
                            words_per_row=142, word_count=len(words),
                            even_pixel_bits='1:0', odd_pixel_bits='3:2',
                            palette_rgb=PALETTE),
                  text=dict(x=400, title_y=24, principle_y=64, cell_width=24,
                            cell_height=24, glyph_count=len(characters),
                            row_word_count=len(rows), row_word_width=24,
                            leftmost_pixel_bit=23, ink_rgb=INK,
                            characters=characters))
    output = {
        'contest_brand_logo_pairs.memh': ''.join(f'{word:x}\n' for word in words).encode(),
        'contest_brand_glyphs.memh': ''.join(f'{row:06x}\n' for row in rows).encode(),
        'contest_brand_layout.svh': ('\n'.join(header) + '\n').encode(),
        'contest_brand_layout.json': (json.dumps(layout, ensure_ascii=False, indent=2) + '\n').encode(),
    }
    preview = Image.new('RGB', (1700, 112), 'white')
    qlogo = Image.new('RGB', (283, 80))
    qlogo.putdata([PALETTE[code] for code in codes])
    preview.paste(qlogo, (64, 24))
    for line, y in [(TITLE, 24), (PRINCIPLE, 64)]:
        for i, character in enumerate(line):
            preview.paste(INK, (400 + i * 24, y), glyphs[character])
    return output, preview


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--font', type=Path, required=True)
    parser.add_argument('--check', action='store_true', help='Verify ROMs without writing.')
    parser.add_argument('--preview', type=Path, help='Optional review image outside source tree.')
    args = parser.parse_args()
    output, preview = generate(args.font)
    for name, data in output.items():
        path = ASSETS / name
        if args.check:
            assert path.read_bytes() == data, f'generated branding drift: {name}'
        else:
            path.write_bytes(data)
    if args.preview:
        preview.save(args.preview)
    print(json.dumps(dict(verified=args.check,
                         output_sha256={name: sha(data) for name, data in output.items()}), indent=2))


if __name__ == '__main__':
    main()
