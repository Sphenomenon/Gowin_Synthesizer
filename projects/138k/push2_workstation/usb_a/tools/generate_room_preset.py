#!/usr/bin/env python3
"""Compile six first-order image sources of a 6x5x3 m room into stereo taps."""
from pathlib import Path
import json,math
ROOT=Path(__file__).resolve().parents[1]
def preset():
    room=(6.0,5.0,3.0);source=(2.0,1.7,1.2);listener=(3.6,3.0,1.3)
    ears=[(listener[0]-.09,listener[1],listener[2]),(listener[0]+.09,listener[1],listener[2])]
    direct=math.dist(source,listener)
    taps=[]
    for wall in range(6):
        axis=wall//2;image=list(source)
        image[axis]=-source[axis] if wall%2==0 else 2*room[axis]-source[axis]
        for ear,position in enumerate(ears):
            distance=math.dist(image,position)
            delay=round((distance-direct)/343*48000)
            assert 0<delay<2048
            gain=round(.20*direct/distance*32768)
            taps.append(dict(wall=wall,ear=ear,delay=delay,gain_q15=gain))
    return dict(sample_rate=48000,speed_of_sound=343,room_m=room,source_m=source,
                listener_m=listener,ear_spacing_m=.18,taps=taps,fdn_delays=[1429,1789,1999,2131])
def main():
    d=preset();folder=ROOT/'rtl/audio'
    text='// Generated by tools/generate_room_preset.py. First-order image-source excess delays.\n'
    for field,name in [('delay','early_delay'),('gain_q15','early_gain')]:
        text+=f'function automatic [15:0] {name}(input [3:0] tap);\n  case(tap)\n'
        text+=''.join(f"    4'd{i}: {name}=16'd{t[field]};\n" for i,t in enumerate(d['taps']))
        text+=f"    default: {name}=16'd0;\n  endcase\nendfunction\n"
    (folder/'spatial_room_preset.svh').write_text(text)
    (folder/'spatial_room_preset.json').write_text(json.dumps(d,indent=2)+'\n')
    print('Stereo early-reflection delays:',[t['delay'] for t in d['taps']])
if __name__=='__main__':main()
