"""Deterministic 1024-point FFT coefficients and logarithmic frequency map."""
from pathlib import Path
import argparse
import math

ROOT = Path(__file__).resolve().parents[1]

def render():
    lines = ["`default_nettype none", "// Generated by scripts/generate_analysis_roms.py; Fs=48,828.125 Hz.",
             "module audio_analysis_rom(input wire clk, input wire [9:0] window_addr,",
             " input wire [8:0] twiddle_addr, input wire [8:0] column_addr,",
             " output reg [15:0] window_gain, output reg signed [17:0] twiddle_re, twiddle_im,",
             " output reg [8:0] frequency_bin);", "always @(posedge clk) begin", " case(window_addr)"]
    for n in range(1024):
        hann = round((0.5 - 0.5 * math.cos(2 * math.pi * n / 1024)) * 65535)
        lines.append(f"  10'd{n}: window_gain <= 16'd{hann};")
    lines += [" endcase", " case(twiddle_addr)"]
    for n in range(512):
        real = max(-131072, min(131071, round(math.cos(2 * math.pi * n / 1024) * 131072)))
        imag = max(-131072, min(131071, round(-math.sin(2 * math.pi * n / 1024) * 131072)))
        word = ((real & 0x3ffff) << 18) | (imag & 0x3ffff)
        lines.append(f"  9'd{n}: {{twiddle_re,twiddle_im}} <= 36'h{word:09x};")
    lines += [" endcase", " case(column_addr)"]
    for n in range(512):
        bin_number = max(1, min(419, round(math.exp(math.log(419) * n / 511))))
        lines.append(f"  9'd{n}: frequency_bin <= 9'd{bin_number};")
    lines += [" endcase", "end", "endmodule", "`default_nettype wire", ""]
    return "\n".join(lines)

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    path = ROOT / "src/video/audio_analysis_rom.v"
    expected = render()
    if args.check:
        assert path.read_text(encoding="utf-8") == expected, "analysis ROMs are stale"
        print("PASS analysis coefficient ROMs")
    else:
        path.write_text(expected, encoding="utf-8", newline="\n")
        print(path)
